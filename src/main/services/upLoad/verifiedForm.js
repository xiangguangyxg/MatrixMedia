/** 仅在字段核验通过后允许提交；编辑器重建时重新取节点，避免旧句柄失效。 */
export async function fillVerifiedText(page, selector, expected) {
  await dismissKnownEditorOverlays(page);
  const normalize = (s) => String(s || '').replace(/\s+/g, ' ').trim();
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const handle = await page.waitForSelector(selector, { timeout: 15000 });
      await handle.click();
      await page.keyboard.down(process.platform === 'darwin' ? 'Meta' : 'Control');
      await page.keyboard.press('KeyA');
      await page.keyboard.up(process.platform === 'darwin' ? 'Meta' : 'Control');
      await page.keyboard.press('Backspace');
      if (expected) await page.keyboard.type(expected, { delay: 20 });
      const actual = await handle.evaluate((el) => el.value == null ? (el.innerText || el.textContent) : el.value);
      if (normalize(actual) === normalize(expected)) return;
      throw new Error('输入内容核验不一致');
    } catch (e) {
      if (attempt === 2 || !/detached|context.*destroyed|核验不一致/i.test(String(e.message))) throw e;
      await page.waitForTimeout(300);
    }
  }
}

/** 关闭已识别的新手引导/满意度弹窗；不处理验证码、安全或协议弹窗。 */
export async function dismissKnownEditorOverlays(page) {
  const count = await page.evaluate(() => {
    const app = document.querySelector('wujie-app.wujie_iframe');
    const roots = [document, app && app.shadowRoot].filter(Boolean);
    let closed = 0;
    for (const root of roots) {
      const tour = root.querySelector('.react-joyride__tooltip button[data-action="close"], .joyride-tooltip button[data-action="close"], [data-test-id="button-close"]');
      if (tour) { tour.click();closed++; }
      for (const heading of root.querySelectorAll('div,p,span,h3')) {
        const text = String(heading.textContent || '').trim();
        const feedback = /^你对PC版创作者服务平台是否满意[？?]?$/.test(text);
        const tourHeading = text === '作品信息';
        if (!feedback && !tourHeading) continue;
        let box = heading;
        for (let level = 0; box && level < 6; level++,box=box.parentElement) {
          if (tourHeading && !/下一步/.test(box.textContent || '')) continue;
          const close = box.querySelector('[class*="close"], [aria-label="关闭"], [aria-label="Close"], [title="关闭"], [data-action="close"]');
          if (close) { close.click();closed++;break; }
        }
        break;
      }
    }
    return closed;
  });
  if (count) { console.log('[publish] 已关闭已识别编辑器遮挡弹窗：'+count);await page.waitForTimeout(300); }
}

/** 只接受可核实成功信号；超时/登录跳转/校验提示均不自动重新提交。 */
export async function waitVerifiedSubmit(page, platform, { timeoutMs = 30000, now = Date.now } = {}) {
  const deadline = now() + timeoutMs;
  do {
    const url = String(page.url() || '');
    if (platform === 'sph' ? /\/platform\/post\/list(?:[/?#]|$)/.test(url) : /\/article\/manage\/video(?:[/?#]|$)/.test(url)) return { ok: true, message: '已返回作品管理页，请核实审核状态' };
    const state = await page.evaluate((pt) => {
      const app = document.querySelector('wujie-app.wujie_iframe');
      const root = pt === 'sph' ? app && app.shadowRoot : document;
      if (!root) return { error: '', success: false };
      const visible = (el) => { const r = el.getBoundingClientRect();return r.width > 0 && r.height > 0; };
      const nodes = Array.from(root.querySelectorAll('[role="alert"],.ant-message-notice,.weui-desktop-toast,.weui-desktop-form__tips,.ant-form-item-explain-error,.weui-desktop-dialog__bd'));
      const texts = nodes.filter(visible).map(el=>String(el.textContent || '').trim()).filter(Boolean);
      return { success: texts.some(s=>/^(发布成功|发表成功|Published successfully|Successfully published)[！!。.]?$/i.test(s)), error: texts.filter(s=>/失败|错误|必填|不能为空|请.{0,20}(填写|选择|验证)|验证码|failed|required|verification/i.test(s)).join('；').slice(0,400) };
    }, platform).catch(()=>({error:'',success:false}));
    if (state.success) return { ok:true,message:'页面明确提示发布成功' };
    if (state.error) return { ok:false,message:'平台未确认发布：'+state.error };
    if (/passport|\/login(?:[/?#]|$)/i.test(url)) return {ok:false,message:'提交后出现登录或验证页面，需要本人处理'};
    await page.waitForTimeout(500);
  } while (now() < deadline);
  return { ok:false,message:'提交后未观察到明确成功信号；请核查后台，勿重复提交' };
}

/** 中英文只匹配同一声明，不按下拉序号或模糊包含词选取。 */
export function statementAliases(label, value) {
  return value === 'ai_generated' ? [label,'AI生成内容','Contains AI-generated content','Contains AI generated content','AI-generated content','AI generated content','Content generated by AI'] : [label];
}
